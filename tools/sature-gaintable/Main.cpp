// Writes Fancy Sature's auto-gain table (docs/sature.md, Decision 6). CMake builds and runs this
// before the plugin compiles, so the table always matches the curves in
// fancy/dsp/Saturation.h.
//
// For every Type, Drive (0-36 dB, 1 dB steps) and Character (-100 to +100 %, steps of 10), it
// renders fixed-seed pink noise at -18 dBFS RMS through the curve and Tape's loss and stores the gain that brings its BS.1770 loudness back to the
// input's. Tone gets its own small table, measured on the same noise.
//
// Usage: sature-gaintable <output header>

#include <fancy/dsp/LoudnessMeter.h>
#include <fancy/dsp/Saturation.h>

#include <cmath>
#include <cstdio>
#include <fstream>
#include <random>
#include <string>
#include <vector>

namespace sat = fancy::dsp::saturation;

namespace
{
constexpr double rate = sat::tableRate;
constexpr int seconds = 2;
constexpr int length = seconds * (int) rate;

std::vector<float> pinkNoise()
{
    std::mt19937 random (18);
    std::uniform_real_distribution<double> uniform (-1.0, 1.0);

    // Paul Kellet's pink filter, with half a second of warm-up dropped.
    const auto warmUp = (int) (0.5 * rate);
    double b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
    std::vector<double> pink;

    for (int i = 0; i < length + warmUp; ++i)
    {
        const auto white = uniform (random);
        b0 = 0.99886 * b0 + white * 0.0555179;
        b1 = 0.99332 * b1 + white * 0.0750759;
        b2 = 0.96900 * b2 + white * 0.1538520;
        b3 = 0.86650 * b3 + white * 0.3104856;
        b4 = 0.55000 * b4 + white * 0.5329522;
        b5 = -0.7616 * b5 - white * 0.0168980;
        const auto value = b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362;
        b6 = white * 0.115926;

        if (i >= warmUp)
            pink.push_back (value);
    }

    auto mean = 0.0;
    for (auto v : pink) mean += v;
    mean /= (double) pink.size();

    auto power = 0.0;
    for (auto& v : pink) { v -= mean; power += v * v; }

    const auto scale = sat::tableNoiseRms / std::sqrt (power / (double) pink.size());

    std::vector<float> out (pink.size());
    for (size_t i = 0; i < pink.size(); ++i)
        out[i] = (float) (pink[i] * scale);

    return out;
}

double loudness (const std::vector<float>& signal)
{
    fancy::dsp::LoudnessMeter meter;
    meter.prepare (rate);
    meter.process (signal.data(), signal.data(), (int) signal.size());
    return meter.getIntegrated();
}

std::string number (double value)
{
    char text[32];
    std::snprintf (text, sizeof (text), "%.4ff", value);
    return text;
}
} // namespace

int main (int argc, char** argv)
{
    if (argc < 2)
    {
        std::fprintf (stderr, "usage: sature-gaintable <output header>\n");
        return 1;
    }

    const auto noise = pinkNoise();
    const auto inputLufs = loudness (noise);
    const auto tapeCoefficient = sat::TapeLoss::coefficientFor (rate);
    std::vector<float> shaped (noise.size());

    std::string text;
    text += "// Generated by tools/sature-gaintable during the build. Do not edit: change the curves in\n";
    text += "// fancy-core/include/fancy/dsp/Saturation.h and rebuild.\n\n";
    text += "#pragma once\n\nnamespace fancy::sature\n{\n\n";
    text += "// Auto gain in dB, by [Type][Drive in dB][(Character + 100) / 10].\n";
    text += "inline constexpr float autoGainDb[" + std::to_string ((int) sat::numTypes) + "][" + std::to_string (sat::tableDrives) + "]["
          + std::to_string (sat::tableCharacters) + "] = {\n";

    for (int type = 0; type < sat::numTypes; ++type)
    {
        text += "    {\n";

        for (int drive = 0; drive < sat::tableDrives; ++drive)
        {
            text += "        { ";
            const auto driveGain = std::pow (10.0, (double) drive / 20.0);
            const auto tapeAmount = sat::TapeLoss::amountFor ((double) drive, type == sat::tape ? 1.0 : 0.0);

            for (int step = 0; step < sat::tableCharacters; ++step)
            {
                const auto curve = sat::makeCurve (type, (double) (step - 10) / 10.0);
                const auto dc = curve.shape (curve.bias);
                sat::TapeLoss loss;

                // The bare curve, without ADAA: at 48 kHz its two-sample average would take about
                // 1 dB off pink noise's top end, which the plugin's subtraction never hears.
                for (size_t i = 0; i < noise.size(); ++i)
                {
                    const auto y = curve.shape (driveGain * (double) noise[i] + curve.bias) - dc;
                    shaped[i] = (float) loss.process (y, tapeCoefficient, tapeAmount);
                }

                text += number (inputLufs - loudness (shaped));
                text += step + 1 < sat::tableCharacters ? ", " : " ";
            }

            text += drive + 1 < sat::tableDrives ? "},\n" : "}\n";
        }

        text += type + 1 < sat::numTypes ? "    },\n" : "    }\n";
    }

    text += "};\n\n// Tone's level change in dB, by Tone + 6.\ninline constexpr float toneGainDb[" + std::to_string (sat::tableTones) + "] = { ";

    for (int tone = 0; tone < sat::tableTones; ++tone)
    {
        sat::TiltCoefficients coefficients;
        coefficients.set ((double) (tone - 6), rate);
        sat::Tilt tilt;

        for (size_t i = 0; i < noise.size(); ++i)
            shaped[i] = (float) tilt.process (coefficients, (double) noise[i]);

        text += number (inputLufs - loudness (shaped));
        text += tone + 1 < sat::tableTones ? ", " : " ";
    }

    text += "};\n\n} // namespace fancy::sature\n";

    std::ofstream file (argv[1], std::ios::binary);
    file << text;

    if (! file.good())
    {
        std::fprintf (stderr, "sature-gaintable: couldn't write %s\n", argv[1]);
        return 1;
    }

    std::printf ("sature-gaintable: wrote %s (input %.2f LUFS)\n", argv[1], inputLufs);
    return 0;
}
